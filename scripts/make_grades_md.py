#!/usr/bin/env python3
"""Render grades.tsv into a human-readable grades.md (legend + per-grade tables).

A reviewer-facing companion to grades.tsv: explains the rubric, then lists the PSMs
grouped by grade with a pass/fail matrix (. = pass, X = fail) and the missed criteria.
"""
import os
import sys
import csv
import argparse
from collections import Counter

PSMV = "/public/groups/carpenterlab/people/emalekos/sORFs/Proteomics/PSM_Verification"
# (pass_column, short label) for the seven "excellent" criteria, in gate order
CRIT = [("cov_pass", "cov"), ("gap_pass", "gap"), ("series_pass", "ser"), ("ppm_pass", "ppm"),
        ("nox_pass", "nox"), ("base_pass", "base"), ("unexp_pass", "unx")]


def mark(v):
    return "." if v == "PASS" else "**X**"


def matrix_cols(r):
    return " | ".join(mark(r[c]) for c, _ in CRIT)


def missed(r):
    return ", ".join(lab for c, lab in CRIT if r[c] == "FAIL") or "—"


def main():
    ap = argparse.ArgumentParser(description="grades.tsv -> grades.md")
    ap.add_argument("--tsv", default=f"{PSMV}/figures_psmplot/grades.tsv")
    ap.add_argument("--out", default=f"{PSMV}/figures_psmplot/grades.md")
    ap.add_argument("--date", default="", help="optional date stamp for the header")
    args = ap.parse_args()

    rows = list(csv.DictReader(open(args.tsv), delimiter="\t"))
    counts = Counter(r["grade"] for r in rows)
    order = ["excellent", "good", "caution", "low_information"]
    hdr = "cov | gap | ser | ppm | nox | base | unx"

    L = []
    L.append("# Flagship PSM grades — manual-validation rubric (Deutsch et al. 2026)")
    L.append("")
    stamp = f" ({args.date})" if args.date else ""
    L.append(f"*Companion to `grades.tsv`{stamp}. Generated by psmplot `make_grades_md.py`.*")
    L.append("")
    L.append("Every reported PSM already passes the statistical bar (Percolator **q < 0.01 AND "
             "PEP < 0.1**). This is the orthogonal, spectrum-level check reviewers asked for: it "
             "grades the **spectrum**, not the identification, as **excellent / good / caution / "
             "low-information** against the manual-validation procedure in Deutsch et al., *Nature* 2026.")
    L.append("")
    L.append("## How the grade is decided")
    L.append("")
    L.append("A spectrum is **excellent** iff it passes **all seven** criteria below; **caution** or "
             "**low-information** if a down-grade trigger fires; otherwise **good**.")
    L.append("")
    L.append("| # | criterion | threshold | column |")
    L.append("|---|---|---|---|")
    L.append("| 1 | sequence coverage | ≥ 90% of cleavage sites | `cov` |")
    L.append("| 2 | longest gap in the b/y ladder | ≤ 1 | `max_gap` |")
    L.append("| 3 | both termini represented | b2 present **or** y-series ≥ len−1 | `series` |")
    L.append("| 4 | precursor mass accuracy | \\|ppm\\| ≤ 12 (≤ 13 for TMT) | `ppm` |")
    L.append("| 5 | modification count | ≤ 2 oxidations | `n_ox` |")
    L.append("| 6 | base peak explained | tallest peak is a benign/explained ion | `base` |")
    L.append("| 7 | no dominant stray peak | largest unexplained < 50% of base | `max_unexp` |")
    L.append("")
    L.append("**Down-grade triggers:** *caution* = a dominant unexplained peak (≥ 60%) **and** an "
             "incomplete ladder (cov < 85%); *low-information* = coverage < 55%.")
    L.append("")
    L.append("The explained/benign model behind criteria 6–7 counts b/y/a ions, water/ammonia losses, "
             "internal fragments, immonium ions, and the whole precursor family (charge-reduced + "
             "isotopes + neutral losses) — so a precursor-loss or co-isolation base peak is *not* "
             "mis-scored as unexplained.")
    L.append("")
    L.append("## Summary")
    L.append("")
    tally = " · ".join(f"**{counts.get(g,0)} {g.replace('_','-')}**" for g in order if counts.get(g))
    L.append(f"**{len(rows)} flagship PSMs** — {tally}.")
    L.append("")
    L.append("Two patterns hold across every PSM:")
    L.append("")
    L.append("- **Mass accuracy (`ppm`) and modification count (`n_ox`) pass on all "
             f"{len(rows)}** — the identifications are not in question; grading is purely about spectral quality.")
    L.append("- **The most common miss is criterion 7** (a lone co-isolation / precursor peak > 50%). "
             "So *good* vs *excellent* is overwhelmingly \"one messy peak,\" not weak sequence evidence — "
             "*good = confident ID with one messy peak; excellent = confident ID and a pristine spectrum.*")
    L.append("")

    labels = {"excellent": "Excellent", "good": "Good", "caution": "Caution", "low_information": "Low-information"}
    for g in order:
        grp = [r for r in rows if r["grade"] == g]
        if not grp:
            continue
        L.append(f"## {labels[g]} ({len(grp)})")
        L.append("")
        if g == "excellent":
            L.append("All seven criteria pass.")
            L.append("")
            L.append("| target | peptide | dataset | z | MS2PIP r | cov | ppm |")
            L.append("|---|---|---|---|---|---|---|")
            for r in grp:
                L.append(f"| {r['target']} | `{r['peptide']}` | {r['dataset']} | {r['charge']} | "
                         f"{r['ms2pip_r']} | {r['cov']} | {r['ppm']} |")
        else:
            L.append(f"`.` = pass, **X** = fail.  Criteria: {hdr}.")
            L.append("")
            L.append(f"| target | peptide | dataset | r | {hdr} | missed |")
            L.append("|---|---|---|---|" + "---|" * 7 + "---|")
            for r in grp:
                L.append(f"| {r['target']} | `{r['peptide']}` | {r['dataset']} | {r['ms2pip_r']} | "
                         f"{matrix_cols(r)} | {missed(r)} |")
        L.append("")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    open(args.out, "w").write("\n".join(L) + "\n")
    print(f"wrote {args.out} ({len(rows)} PSMs; {dict(counts)})")


if __name__ == "__main__":
    main()
